#define OLED_WIDTH   128
#define OLED_HEIGHT  64
#define OLED_LINES   (OLED_HEIGHT / 8)   // 8 dong (moi dong = 1 "page" cua SSD1306)
#define OLED_COLS    (OLED_WIDTH / 6)    // 21 ky tu moi dong (moi ky tu rong 6 pixel)

typedef struct {
    i2c_dev_t dev;
    uint8_t buf[OLED_WIDTH * OLED_LINES];   // bo nho dem 1024 byte
} oled_t;

