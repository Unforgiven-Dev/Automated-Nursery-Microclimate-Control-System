// Gui 1 chuoi lenh (control byte 0x00)
static inline esp_err_t oled_send_cmds(oled_t *o, const uint8_t *cmds, size_t len)
{
    const uint8_t ctrl = 0x00;
    I2C_DEV_TAKE_MUTEX(&o->dev);
    I2C_DEV_CHECK(&o->dev, i2c_dev_write(&o->dev, &ctrl, 1, cmds, len));
    I2C_DEV_GIVE_MUTEX(&o->dev);
    return ESP_OK;
}

static inline void oled_clear(oled_t *o)
{
    memset(o->buf, 0, sizeof(o->buf));
}

// Day bo nho dem ra man hinh (tung dong mot)
static inline esp_err_t oled_flush(oled_t *o)
{
    for (int page = 0; page < OLED_LINES; page++) {
        const uint8_t set_pos[3] = { (uint8_t)(0xB0 | page), 0x00, 0x10 };   // chon dong, cot 0
        esp_err_t err = oled_send_cmds(o, set_pos, sizeof(set_pos));
        if (err != ESP_OK) {
            return err;
        }

        const uint8_t ctrl = 0x40;   // control byte 0x40 = du lieu hien thi
        I2C_DEV_TAKE_MUTEX(&o->dev);
        I2C_DEV_CHECK(&o->dev, i2c_dev_write(&o->dev, &ctrl, 1, &o->buf[page * OLED_WIDTH], OLED_WIDTH));
        I2C_DEV_GIVE_MUTEX(&o->dev);
    }
    return ESP_OK;
}

// Khoi tao man hinh. addr thuong la 0x3C (mot so module la 0x3D)
static inline esp_err_t oled_init(oled_t *o, uint8_t addr, i2c_port_t port, gpio_num_t sda, gpio_num_t scl)
{
    memset(o, 0, sizeof(*o));
    o->dev.port = port;
    o->dev.addr = addr;
    o->dev.cfg.sda_io_num = sda;
    o->dev.cfg.scl_io_num = scl;
    o->dev.cfg.master.clk_speed = 400000;

    esp_err_t err = i2c_dev_create_mutex(&o->dev);
    if (err != ESP_OK) {
        return err;
    }

    static const uint8_t init_seq[] = {
        0xAE,         // tat hien thi
        0xD5, 0x80,   // toc do clock
        0xA8, 0x3F,   // multiplex 64 dong
        0xD3, 0x00,   // khong dich man hinh
        0x40,         // dong bat dau = 0
        0x8D, 0x14,   // bat charge pump (bat buoc voi module 0.96 inch)
        0x20, 0x02,   // che do dia chi theo page
        0xA1,         // dao chieu cot (doi thanh 0xA0 neu chu bi lat guong)
        0xC8,         // dao chieu dong (doi thanh 0xC0 neu chu bi lon nguoc)
        0xDA, 0x12,   // cau hinh chan COM
        0x81, 0xCF,   // do tuong phan
        0xD9, 0xF1,   // pre-charge
        0xDB, 0x40,   // muc VCOMH
        0xA4,         // hien thi theo bo nho
        0xA6,         // hien thi binh thuong (khong dao mau)
        0xAF          // bat hien thi
    };
    err = oled_send_cmds(o, init_seq, sizeof(init_seq));
    if (err != ESP_OK) {
        return err;
    }

    oled_clear(o);
    return oled_flush(o);
}

// Ve 1 ky tu tai o (col, line)
static inline void oled_put_char(oled_t *o, int col, int line, char c)
{
    if (col < 0 || col >= OLED_COLS || line < 0 || line >= OLED_LINES) {
        return;
    }
    if (c < 32 || c > 126) {
        c = '?';
    }
    uint8_t *dst = &o->buf[line * OLED_WIDTH + col * 6];
    memcpy(dst, &OLED_FONT_5X7[(c - 32) * 5], 5);
    dst[5] = 0x00;   // cot trong giua 2 ky tu
}

// Ghi chuoi tai (col, line)
static inline void oled_print(oled_t *o, int col, int line, const char *text)
{
    for (; *text && col < OLED_COLS; text++, col++) {
        oled_put_char(o, col, line, *text);
    }
}

// Xoa 1 dong roi ghi noi dung moi theo dinh dang printf
static inline void oled_printf(oled_t *o, int line, const char *fmt, ...) __attribute__((format(printf, 3, 4)));
static inline void oled_printf(oled_t *o, int line, const char *fmt, ...)
{
    if (line < 0 || line >= OLED_LINES) {
        return;
    }
    char text[OLED_COLS + 1];
    va_list args;
    va_start(args, fmt);
    vsnprintf(text, sizeof(text), fmt, args);
    va_end(args);

    memset(&o->buf[line * OLED_WIDTH], 0, OLED_WIDTH);
    oled_print(o, 0, line, text);
}
